/**
 * Writes supabase/migrations/20261009000100_seed_cms_pages.sql from
 * supabase/seed/pages.ts.   Run: npm run seed:sql
 *
 * The migration is idempotent: a page is only created when no live page
 * already uses its path, so re-running it never overwrites the client's edits.
 */
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { seedPages } from '../supabase/seed/pages.ts'
import { servicePages } from '../supabase/seed/service-pages.ts'

export const OUTPUT = 'supabase/migrations/20261009000100_seed_cms_pages.sql'
export const SERVICE_OUTPUT = 'supabase/migrations/20261013000000_service_pages.sql'

/** Stable ids so regenerating the file produces the same SQL. */
function stableUuid(seed: string): string {
  const h = createHash('sha1').update(`pipeflow-seed:${seed}`).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`
}

const q = (value: string) => {
  // $tag$$tag$ is ambiguous to Postgres, so the empty homepage path is written as ''.
  if (value === '') return "''"
  if (value.includes('$cms_seed$')) throw new Error('seed text must not contain $cms_seed$')
  return `$cms_seed$${value}$cms_seed$`
}
const nullable = (value?: string) => (value ? q(value) : 'NULL')

export function buildSeedSql(): string {
  const blocks = seedPages.map((page) => {
    const sections = page.sections.map((s, i) => ({ id: stableUuid(`${page.path}#${i}`), ...s }))
    const publish = page.isTemplate || page.draft ? '' : '    PERFORM cms_publish(v_id, 1, NULL);\n'
    // Purane address par page abhi bhi hai (move migration nahi chali) to naya copy mat banao.
    const match = page.legacyPaths?.length ? `path IN (${[page.path, ...page.legacyPaths].map(q).join(', ')})` : `path = ${q(page.path)}`
    return `DO $$
DECLARE v_id UUID;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM cms_pages WHERE ${match} AND deleted_at IS NULL) THEN
    v_id := cms_create_page(
      ${q(page.title)},
      ${q(page.path)},
      ${nullable(page.description)},
      ${q(JSON.stringify(sections))}::jsonb,
      ${nullable(page.seoTitle)},
      ${nullable(page.seoDescription)},
      NULL,
      NULL,
      ${page.noindex ? 'true' : 'false'},
      ${page.isTemplate ? 'true' : 'false'},
      NULL
    );
${publish}  END IF;
END $$;
`
  })
  return `-- GENERATED by scripts/generate-seed-sql.ts from supabase/seed/pages.ts. Do not edit by hand.
-- Launch pages built from the client's documents. Safe to re-run: existing paths are left alone.
-- Pages whose copy is still a starter are published with noindex set, so search engines skip
-- them until the client writes the real content and clears that box in the editor.

${blocks.join('\n')}`
}

/**
 * The eight-page service set (category and individual-service templates). New pages are DRAFTs.
 * Existing paths are reported with their current state and left untouched for reconciliation.
 */
export function buildServicePagesSql(): string {
  const blocks = servicePages.map((page) => {
    const sections = [{ id: stableUuid(`${page.path}#0`), type: page.type, data: page.data }]
    return `DO $$
DECLARE
  v_id UUID;
  v_existing cms_pages%ROWTYPE;
BEGIN
  SELECT * INTO v_existing
  FROM cms_pages
  WHERE path = ${q(page.path)} AND deleted_at IS NULL
  FOR UPDATE;

  IF NOT FOUND THEN
    v_id := cms_create_page(
      ${q(page.title)},
      ${q(page.path)},
      ${q(page.description)},
      ${q(JSON.stringify(sections))}::jsonb,
      ${q(page.seoTitle)},
      ${q(page.seoDescription)},
      NULL,
      NULL,
      false,
      false,
      NULL
    );
  ELSE
    RAISE NOTICE 'service page seed skipped existing record: path=%, id=%, status=%, is_template=%, version=%, draft_revision_id=%, published_revision_id=%',
      v_existing.path, v_existing.id, v_existing.status, v_existing.is_template,
      v_existing.version, v_existing.draft_revision_id, v_existing.published_revision_id;
  END IF;
END $$;
`
  })
  return `-- GENERATED by scripts/generate-seed-sql.ts from supabase/seed/service-pages.ts. Do not edit by hand.
-- Plumbing and HVAC service pages. Existing paths are reported and left untouched for manual review.
-- All eight inserts run in one transaction; preview and publish each new draft in the admin.

BEGIN;
SET LOCAL lock_timeout = '10s';

${blocks.join('\n')}
COMMIT;
`
}

// Only write files when run directly, not when a test imports the generators.
if (process.argv[1]?.endsWith('generate-seed-sql.ts')) {
  const serviceOnly = process.argv.includes('--service-only')
  if (!serviceOnly) {
    writeFileSync(OUTPUT, buildSeedSql())
    console.log(`Wrote ${OUTPUT} (${seedPages.length} pages)`)
  }
  writeFileSync(SERVICE_OUTPUT, buildServicePagesSql())
  console.log(`Wrote ${SERVICE_OUTPUT} (${servicePages.length} pages)`)
}
